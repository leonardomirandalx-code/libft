#include "libft.h"

char	*ft_strmapi(char const *s, char (*f) (unsigned int, char))
{
	size_t	i;
	char	*string;

	if (!s || !f)
		return (NULL);
	i = 0;
	string = malloc(ft_strlen(s) + 1);
	if (string == NULL)
		return (NULL);
	while (s[i])
	{
		string[i] = f(i, s[i]);
		i++;
	}
	string[i] = '\0';
	return (string);
}
